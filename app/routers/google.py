"""FastAPI routes for Google Calendar OAuth, event sync, and notifications."""
import secrets
from datetime import datetime, timezone, timedelta
from typing import Optional
from fastapi import APIRouter, HTTPException
from fastapi.responses import RedirectResponse
from google_auth_oauthlib.flow import Flow
from app.config import (
    GOOGLE_CLIENT_ID,
    GOOGLE_CLIENT_SECRET,
    GOOGLE_REDIRECT_URI,
    SCOPES,
)
from app.db import get_conn
from app.schemas import GCalEventRequest
from app.services import gcal

router = APIRouter(prefix="/api/google", tags=["google"])


@router.get("/auth")
def google_auth():
    """Initiate Google OAuth flow with PKCE."""
    if not GOOGLE_CLIENT_ID or not GOOGLE_CLIENT_SECRET:
        raise HTTPException(
            status_code=503,
            detail="Google OAuth not configured. Set GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET."
        )

    flow = Flow.from_client_config(
        client_config={
            "web": {
                "client_id": GOOGLE_CLIENT_ID,
                "client_secret": GOOGLE_CLIENT_SECRET,
                "auth_uri": "https://accounts.google.com/o/oauth2/auth",
                "token_uri": "https://oauth2.googleapis.com/token",
                "redirect_uris": [GOOGLE_REDIRECT_URI],
            }
        },
        scopes=SCOPES,
        redirect_uri=GOOGLE_REDIRECT_URI,
    )

    state = secrets.token_urlsafe(16)
    auth_url, _ = flow.authorization_url(
        access_type="offline",
        include_granted_scopes="true",
        prompt="consent",
        state=state,
    )
    # Store PKCE code_verifier generated by flow
    gcal.get_oauth_states()[state] = getattr(flow, "code_verifier", None)
    return RedirectResponse(auth_url)


@router.get("/callback")
def google_callback(code: str, state: str = "", error: str = ""):
    """Handle OAuth callback and store tokens."""
    if error:
        return RedirectResponse(f"/?gcal_error={error}")

    oauth_states = gcal.get_oauth_states()
    if state not in oauth_states:
        raise HTTPException(status_code=400, detail="Invalid OAuth state")
    code_verifier = oauth_states.pop(state, None)

    flow = Flow.from_client_config(
        client_config={
            "web": {
                "client_id": GOOGLE_CLIENT_ID,
                "client_secret": GOOGLE_CLIENT_SECRET,
                "auth_uri": "https://accounts.google.com/o/oauth2/auth",
                "token_uri": "https://oauth2.googleapis.com/token",
                "redirect_uris": [GOOGLE_REDIRECT_URI],
            }
        },
        scopes=SCOPES,
        redirect_uri=GOOGLE_REDIRECT_URI,
        state=state,
    )

    if code_verifier:
        flow.fetch_token(code=code, code_verifier=code_verifier)
    else:
        flow.fetch_token(code=code)

    creds = flow.credentials
    gcal.persist_credentials(creds)
    return RedirectResponse("/?gcal_connected=true")


@router.get("/status")
def google_status():
    """Check if Google Calendar is connected."""
    connected = gcal.get_google_credentials() is not None
    email = None

    if connected:
        service = gcal.get_gcal_service()
        if service:
            try:
                cal_list = service.calendarList().get(calendarId="primary").execute()
                email = cal_list.get("id")
            except Exception:
                connected = False
                gcal.set_google_credentials(None)

    return {"connected": connected, "email": email}


@router.delete("/disconnect")
def google_disconnect():
    """Disconnect Google Calendar."""
    gcal.set_google_credentials(None)
    try:
        conn = get_conn()
        conn.execute("DELETE FROM google_tokens WHERE id = 1")
        conn.commit()
    except Exception:
        pass
    return {"status": "disconnected"}


@router.post("/events")
def create_gcal_event(req: GCalEventRequest):
    """Manually create a Google Calendar event for a task."""
    service = gcal.get_gcal_service()
    if not service:
        raise HTTPException(status_code=401, detail="Google Calendar not connected")

    try:
        event_body = {
            "summary": req.summary,
            "description": req.description or "",
            "start": {"dateTime": req.start_datetime, "timeZone": req.timezone},
            "end": {"dateTime": req.end_datetime, "timeZone": req.timezone},
            "reminders": {
                "useDefault": False,
                "overrides": [
                    {"method": "popup", "minutes": req.reminder_minutes},
                    {"method": "email", "minutes": req.reminder_minutes * 2},
                ],
            },
        }
        if req.recurrence:
            event_body["recurrence"] = gcal.build_recurrence_rule(req.recurrence)

        event = service.events().insert(calendarId="primary", body=event_body).execute()
        event_id = event.get("id")

        # Link gcal_event_id to task in DB
        if req.task_id:
            conn = get_conn()
            conn.execute(
                "UPDATE tasks SET gcal_event_id = ? WHERE id = ?",
                (event_id, req.task_id)
            )
            conn.commit()

        return {"status": "created", "event_id": event_id, "event_link": event.get("htmlLink")}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/events")
def list_gcal_events(time_min: Optional[str] = None, time_max: Optional[str] = None, max_results: int = 250):
    """Fetch events from Google Calendar with optional date range."""
    service = gcal.get_gcal_service()
    if not service:
        raise HTTPException(status_code=401, detail="Google Calendar not connected")

    try:
        if not time_min:
            time_min = (datetime.now(timezone.utc) - timedelta(days=60)).isoformat()
        if not time_max:
            time_max = (datetime.now(timezone.utc) + timedelta(days=365)).isoformat()

        if len(time_min) == 10:
            time_min += "T00:00:00Z"
        if len(time_max) == 10:
            time_max += "T23:59:59Z"

        events_result = service.events().list(
            calendarId="primary",
            timeMin=time_min,
            timeMax=time_max,
            maxResults=max_results,
            singleEvents=True,
            orderBy="startTime",
        ).execute()

        events = []
        for e in events_result.get("items", []):
            start = e["start"].get("dateTime", e["start"].get("date"))
            end = e["end"].get("dateTime", e["end"].get("date"))
            events.append({
                "id": e.get("id"),
                "summary": e.get("summary", "(No title)"),
                "start": start,
                "end": end,
                "link": e.get("htmlLink"),
                "description": e.get("description", ""),
                "is_all_day": "date" in e["start"],
            })
        return {"events": events}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.delete("/events/{event_id}")
def delete_gcal_event(event_id: str):
    """Delete a Google Calendar event."""
    service = gcal.get_gcal_service()
    if not service:
        raise HTTPException(status_code=401, detail="Google Calendar not connected")
    try:
        service.events().delete(calendarId="primary", eventId=event_id).execute()
        return {"status": "deleted"}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
